CREATE TABLE IF NOT EXISTS awz_banobots_ban (
    ID SERIAL PRIMARY KEY,
    DATE_BAN TIMESTAMP NULL DEFAULT NULL,
    IP VARCHAR(50) NOT NULL DEFAULT '',
    COUNTRY VARCHAR(10) NOT NULL DEFAULT '',
    USER_AGENT VARCHAR(500) NOT NULL DEFAULT '',
    ACTIVE CHAR(1) NOT NULL DEFAULT 'Y'
    );
CREATE INDEX IF NOT EXISTS AWZ_BANOBOTS_BAN_IP ON awz_banobots_ban (IP);
CREATE INDEX IF NOT EXISTS AWZ_BANOBOTS_BAN_ACTIVE ON awz_banobots_ban (ACTIVE);
